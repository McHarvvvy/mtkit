// Package peephole 是“后门观察”工具：仅在无法用前门接口验证系统正确性时，直查底层存储
// （MySQL / Redis / Mongo 等）作兜底（你项目里的 test/fixture/peephole）。
//
// 定位（重要，避免误用）：
//   - **前门优先**：凡有对应读接口（典型如 set 必有 get），一律走前门——用 get 验 set。前门读直接写在
//     用例侧（与 setNickname 等请求 helper 同处），不进本包。前门读顺带验证了读链路（缓存读穿、写后失效）
//     整条对外可见性，信心高于“后门只看存储某格被填上”。
//   - **后门兜底**：只有当某状态确实没有任何前门接口可观察时，才在此封装直查存储的 helper。它是万不得已
//     的兜底、尽量少用——后门断言耦合 SQL 列 / cache key 等内部实现，易随重构碎裂、且掩盖读链路 bug。
//
// 本玩具示例没有需要后门观察的状态（昵称有 getNickname 前门），故本包暂无 helper——它作为“文档化空包”
// 存在，提醒你这条优先级；确有需要时按存储域分文件新增。
